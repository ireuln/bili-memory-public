#requires -version 5.1
<#
  Verify the release files against SHA256SUMS.txt (generated by build-release.ps1).

    powershell.exe -NoProfile -ExecutionPolicy Bypass -File .\verify-files.ps1

  Exit codes: 0 clean, 1 mismatch/missing, 2 no manifest (source checkout).
#>
[CmdletBinding()]
param()

$ErrorActionPreference = 'Stop'
# --- encoding bootstrap -------------------------------------------------------
# A child PowerShell writes its output as UTF-8 while the parent decodes with
# the ANSI code page, which is how "access denied" turns into mojibake in an
# error dialog. Both sides agreeing on UTF-8 avoids that. A hidden process has
# no console, hence the catch.
try {
    $script:OutEncoding = New-Object System.Text.UTF8Encoding($false)
    [Console]::OutputEncoding = $script:OutEncoding
    $OutputEncoding = $script:OutEncoding
} catch { }
# -----------------------------------------------------------------------------
$Root = Split-Path -Parent $PSCommandPath
$Sums = Join-Path $Root 'SHA256SUMS.txt'
if (-not (Test-Path $Sums)) {
    Write-Host 'SHA256SUMS.txt not found (source checkout); nothing to verify.'
    exit 2
}

$bad = 0
$checked = 0
foreach ($line in [System.IO.File]::ReadAllLines($Sums, [System.Text.Encoding]::UTF8)) {
    $s = $line.Trim()
    if (-not $s) { continue }
    $i = $s.IndexOf('  ')
    if ($i -lt 0) { continue }
    $expected = $s.Substring(0, $i).Trim().ToLowerInvariant()
    $rel = $s.Substring($i + 2).Trim()
    $path = Join-Path $Root ($rel -replace '/', '\')
    $checked++
    if (-not (Test-Path $path)) {
        Write-Host ('MISSING ' + $rel) -ForegroundColor Red
        $bad++
        continue
    }
    $actual = (Get-FileHash -LiteralPath $path -Algorithm SHA256).Hash.ToLowerInvariant()
    if ($actual -ne $expected) {
        Write-Host ('CHANGED ' + $rel) -ForegroundColor Red
        $bad++
    }
}

if ($bad -gt 0) {
    Write-Host ('FAILED: ' + $bad + ' of ' + $checked + ' file(s) missing or changed.') -ForegroundColor Red
    Write-Host 'If your antivirus quarantined a file, restore it and add the folder to the trust list.'
    exit 1
}
Write-Host ('OK: ' + $checked + ' file(s) match.') -ForegroundColor Green
exit 0
